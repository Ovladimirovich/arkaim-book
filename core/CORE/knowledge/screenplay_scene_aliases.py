"""Утверждённая таблица соответствий имён персонажей сценария.

Таблица зафиксирована владельцем проекта (OWNER-GO) и является единственным
разрешённым основанием для приведения написаний к каноническому имени.

Правила, зафиксированные владельцем:
  - ``Велиусмус``, ``Великосвет``, ``Велом``, ``Вел``, ``Велика`` → ``Велик``
  - ``Владислав`` → ``Влад``
  - ``Вероника`` → ``Вера``
  - ``Мирослав``, ``Славик`` → ``Славный``
  - ``гиперборейцы`` → ``Гипербореи``
  - ``Ученики`` → ``Ученики (плеяда)``  (решение владельца G8, 2026-10-22)

Намеренно НЕ объединяются: ``Архат``/``Учитель``,
``Учитель``/``Учитель Человечества``/``Посредник``, ``Свет``/``Световит``.
Слово ``Слава`` — обычное слово, а не имя персонажа.

Решение владельца G7a (2026-10-22): ``Велика`` — падежная форма того же
имени, отдельной сущности нет. Написание перенесено из отдельного канона
в RAG-реестре (``intelligence/nameresolver.py``) в эту таблицу, чтобы
соответствия «Велика» → «Велик» нельзя было разъехать в двух реестрах.

Решение владельца G8 (2026-10-22): ``Ученики`` и ``Ученики (плеяда)`` —
одно и то же; короткое написание приведено к полному через эту таблицу.

Модуль не хранит состояния и не читает файлы: это только соглашение.
"""

from __future__ import annotations

#: Утверждённые владельцем соответствия «написание в сценарии → каноническое имя».
APPROVED_ALIASES: dict[str, tuple[str, ...]] = {
    "Велик": ("Велиусмус", "Великосвет", "Велом", "Вел", "Велика"),
    "Влад": ("Владислав",),
    "Вера": ("Вероника",),
    "Славный": ("Мирослав", "Славик"),
    "Гипербореи": ("гиперборейцы",),
    "Ученики (плеяда)": ("Ученики",),
}

#: Правила поиска упоминаний: (регулярное выражение, каноническое имя,
#: допустимо ли строчное написание). Регулярные выражения учитывают
#: падежные формы и не затрагивают слова с приставкой.
TERM_SPECS: tuple[tuple[str, str, bool], ...] = (
    (r"Велиусмус\w*", "Велик", False),
    (r"Великосвет\w*", "Велик", False),
    (r"Велом\w*", "Велик", False),
    (r"Вел", "Велик", False),
    (r"Владислав\w*", "Влад", False),
    (r"Вероник\w*", "Вера", False),
    (r"Мирослав\w*", "Славный", False),
    (r"Славик\w*", "Славный", False),
    (r"гиперборейц\w*", "Гипербореи", True),
    (r"Гипербореи\w*", "Гипербореи", False),
    (r"Велик(?:а|у|ом|е)?", "Велик", False),
    (r"Влад(?:а|у|ом|е)?", "Влад", False),
    (r"Вер(?:а|ы|е|у|ой)", "Вера", False),
    (r"Славн(?:ый|ого|ому|ым|ом)", "Славный", False),
    (r"Архат\w*", "Архат", False),
    (r"Учитель Человечества", "Учитель Человечества", False),
    (r"Учителя Истины", "Учителя Истины", False),
    (r"Учител(?:ь|я|ю|ем|е)", "Учитель", False),
    (r"Световит\w*", "Световит", False),
    (r"Святослав\w*", "Святослав", False),
    (r"Любомир\w*", "Любомир", False),
    (r"Яснобор\w*", "Яснобор", False),
    (r"Коловед\w*", "Коловед", False),
    (r"Радомир\w*", "Радомир", False),
    (r"Старост\w*", "Староста", False),
    (r"Посредник\w*", "Посредник", False),
    (r"Наставник\w*", "Наставники", False),
    (r"Ученик(?:и|ов|ам|ами|ах)", "Ученики", False),
)


def alias_surfaces(canonical: str) -> tuple[str, ...]:
    """Возвращает утверждённые написания, отображаемые в каноническое имя."""
    return APPROVED_ALIASES.get(canonical, ())


def canonical_for_surface(surface: str) -> str | None:
    """Возвращает каноническое имя для утверждённого написания (или None)."""
    for canonical, surfaces in APPROVED_ALIASES.items():
        if surface in surfaces:
            return canonical
    return None
